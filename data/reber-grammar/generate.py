# Reber grammar: generation of grammatical and ungrammatical strings.
#
# Reads the grammar from grammar.csv and writes
#
#   reber.txt       grammatical strings, generated by random walks
#                      through the grammar with uniform branching
#   non-reber.txt   ungrammatical strings, each derived from a separately
#                      generated grammatical string by substituting one
#                      inner letter
#
# One string per line.
#
# The random seed is fixed, so the files are reproducible. Requires only the
# Python standard library.
#
# Usage: python3 generate.py


import os
import csv
import random


SEED = 1967          # year of Reber's original study
N_VALID = 100000
N_INVALID = 10000

START = "end"        # the grammar is cyclic: every string starts and ends in "end"
LETTERS = "TPSXV"    # letters that may be substituted (B and E are fixed)


def load_grammar(path):
    with open(path, newline="") as f:
        return {(r["state"], r["letter"]): r["next"] for r in csv.DictReader(f)}


def grammatical(table, string):
    state = START
    for letter in string:
        state = table.get((state, letter))
        if state is None:
            return False
    return state == START


def generate(successors, rng):
    # Random walk from the start state back to the start state
    state, letters = START, []
    while True:
        letter, state = rng.choice(successors[state])
        letters.append(letter)
        if state == START:
            return "".join(letters)


def substitute(table, string, rng):
    # Replace one inner letter so that the string leaves the grammar
    while True:
        i = rng.randrange(1, len(string) - 1)
        letter = rng.choice(LETTERS.replace(string[i], ""))
        s = string[:i] + letter + string[i + 1:]
        if not grammatical(table, s):
            return s


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    table = load_grammar(os.path.join(here, "grammar.csv"))

    successors = {}
    for (state, letter), nxt in sorted(table.items()):
        successors.setdefault(state, []).append((letter, nxt))

    rng = random.Random(SEED)

    valid = [generate(successors, rng) for _ in range(N_VALID)]

    # Invalid strings are derived from new grammatical strings, not from
    # reber.txt, so that the two files are independent samples.
    invalid = [substitute(table, generate(successors, rng), rng)
               for _ in range(N_INVALID)]

    for name, strings in [("reber.txt", valid), ("non-reber.txt", invalid)]:
        with open(os.path.join(here, name), "w") as f:
            f.write("\n".join(strings) + "\n")

    lengths = [len(s) for s in valid]
    print(f"reber.txt:   {N_VALID} strings, {len(set(valid))} distinct, "
          f"length {min(lengths)}-{max(lengths)}, mean {sum(lengths) / N_VALID:.2f}")
    print(f"non-reber.txt: {N_INVALID} strings, {len(set(invalid))} distinct")


if __name__ == "__main__":
    main()
